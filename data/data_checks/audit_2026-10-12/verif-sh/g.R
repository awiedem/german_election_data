suppressMessages(library(dplyr))
e<-bundeslaendeR::ltw_elections%>%distinct(state,election_date,electorate,number_of_voters,valid_votes)
m<-bundeslaendeR::link_gerda%>%distinct(state_gerda,state)
x<-readRDS("data/state_elections/final/state_unharm.rds")
g<-x%>%filter(!(state=="11"&FALSE))%>%group_by(state,election_year,election_date)%>%summarise(n=n(),el=sum(eligible_voters,na.rm=T),nv=sum(number_voters,na.rm=T),va=sum(valid_votes,na.rm=T),nnaV=sum(is.na(number_voters)),.groups="drop")
b<-e%>%inner_join(m,by="state")%>%mutate(state=state_gerda)%>%select(-state_gerda)
j<-g%>%left_join(b,by=c("state","election_year"=NA_character_)[0])%>%mutate()
b$election_year<-as.integer(format(b$election_date,"%Y"))
g$election_year<-as.integer(g$election_year)
j<-inner_join(g,b,by=c("state","election_year"),suffix=c("",".bl"))
j<-j%>%mutate(dv=va/valid_votes-1,de=el/electorate-1,dn=nv/number_of_voters-1,ddate=as.numeric(as.Date(election_date)-election_date.bl))
