suppressMessages(library(dplyr))
u <- readRDS("data/municipal_elections/final/municipal_unharm.rds")
options(width=250)
b <- u %>% filter(eligible_voters>=20000, !state %in% c("02","04","11"))
r <- b %>% group_by(state,election_year) %>% summarise(n=n(),cdu=mean(is.na(cdu_csu)),spd=mean(is.na(spd)),linke=mean(is.na(linke_pds)),gru=mean(is.na(gruene)),fdp=mean(is.na(fdp)),afd=mean(is.na(afd)),other=mean(is.na(other)),.groups="drop")
print(as.data.frame(r %>% filter(election_year>=1990, cdu>0.1|spd>0.1|linke>0.3|gru>0.15|fdp>0.2)),digits=2)
x <- u %>% filter(state=="16",election_year==2019)
cat("TH2019 linke NA:",sum(is.na(x$linke_pds)),"of",nrow(x)," seats linke>0:",sum(x$seats_linke_pds>0,na.rm=T),"\n")
print(x %>% filter(is.na(linke_pds),seats_linke_pds>0) %>% select(ags,ags_name,eligible_voters,seats_linke_pds,replaced_0_with_na_linke_pds,other) %>% head(8) %>% as.data.frame)
y <- u %>% filter(state=="16") %>% group_by(election_year) %>% summarise(linkeNA=mean(is.na(linke_pds)),n=n(),replaced=mean(replaced_0_with_na_linke_pds,na.rm=T),has_seats=sum(seats_linke_pds>0,na.rm=T))
print(as.data.frame(y))
