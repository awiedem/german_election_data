fu<-readRDS("data/federal_elections/municipality_level/final/federal_muni_unharm.rds")
mu<-readRDS("data/municipal_elections/final/municipal_unharm.rds")
print(table(mu$election_type))
f<-fu%>%filter(election_year>=1990)%>%select(ags,fy=election_year,fe=eligible_voters_orig)
m<-mu%>%filter(!is.na(eligible_voters),eligible_voters>0)%>%select(ags,my=election_year,me=eligible_voters,mv=number_voters,vv=valid_votes,state,election_type)
j<-inner_join(m,f,by="ags",relationship="many-to-many")%>%filter(abs(my-fy)<=1,fe>0)%>%mutate(r=me/fe)
cat("pairs",nrow(j),"\n")
g<-j%>%group_by(state,my,fy)%>%summarise(n=n(),tot=sum(me)/sum(fe),med=median(r),out=mean(r<.75|r>1.35),.groups="drop")
print(as.data.frame(g%>%filter(abs(tot-1)>.08|out>.1)),digits=3)
cat("tot ratio dist by state:");print(as.data.frame(j%>%group_by(state)%>%summarise(n=n(),med=median(r),p5=quantile(r,.05),p95=quantile(r,.95))),digits=3)
