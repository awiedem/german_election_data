# ags_name differences
nm<-bind_rows(fh%>%transmute(ags,n=ags_name,src="fed"),sh%>%transmute(ags,n=ags_name,src="state"),mh%>%transmute(ags,n=ags_name,src="muni"))%>%distinct()%>%filter(!is.na(n))
nn<-nm%>%group_by(ags)%>%summarise(k=n_distinct(tolower(trimws(n))),.groups="drop")
