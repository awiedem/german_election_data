setwd("/Users/hanno/Documents/GitHub/german_election_data")
fu<-readRDS("data/federal_elections/municipality_level/final/federal_muni_unharm.rds")
su<-readRDS("data/state_elections/final/state_unharm.rds")
eu<-readRDS("data/european_elections/final/european_muni_unharm.rds")
mu<-readRDS("data/municipal_elections/final/municipal_unharm.rds")
cat("types:\n");print(sapply(list(fu=fu$ags,su=su$ags,eu=eu$ags,mu=mu$ags),function(x)paste(class(x),paste(unique(nchar(x)),collapse="/"))))
cat("fed years\n");print(table(fu$election_year))
# eligible fed vs state: nearest pair by ags
f<-fu%>%transmute(ags,fy=election_year,fe=eligible_voters,fe0=eligible_voters_orig,fn=number_voters)
s<-su%>%transmute(ags,sy=election_year,se=eligible_voters,sn=number_voters,state)
j<-inner_join(f,s,by="ags",relationship="many-to-many")%>%filter(abs(fy-sy)<=1, !is.na(fe),!is.na(se),fe>0,se>0)%>%mutate(r=se/fe)
cat("fed-state pairs",nrow(j),"\n");print(quantile(j$r,c(0,.001,.01,.05,.5,.95,.99,.999,1)))
j2<-j%>%group_by(sy,fy,state)%>%summarise(n=n(),med=median(r),p5=quantile(r,.05),p95=quantile(r,.95),.groups="drop")
print(as.data.frame(j2%>%filter(abs(med-1)>0.03|p5<.85|p95>1.15)),row.names=F)
cat("extreme ratios >1.5 or <.67:",sum(j$r>1.5|j$r<.67),"\n")
print(head(as.data.frame(j%>%filter(r>2|r<.5)%>%arrange(desc(abs(log(r))))),25))
saveRDS(j,file.path("/private/tmp/claude-501/-Users-hanno-Documents-GitHub-german-election-data/adfc9cc1-5d71-47c2-9e9e-f58b91334ee3/scratchpad/audit/xd","j_fs.rds"))
