suppressMessages(library(dplyr))
setwd("/Users/hanno/Documents/GitHub/german_election_data")
fu<-readRDS("data/federal_elections/municipality_level/final/federal_muni_unharm.rds")
fc<-readRDS("data/federal_elections/county_level/final/federal_cty_unharm.rds")
cat(names(fu)[1:60],"\n"); print(names(fc)[1:12]); print(table(fc$year))
fu$cty<-substr(fu$ags,1,5)
m<-fu%>%group_by(state,election_year)%>%summarise(ev=sum(eligible_voters,na.rm=T),ev0=sum(eligible_voters_orig,na.rm=T),nv=sum(number_voters,na.rm=T),vv=sum(valid_votes,na.rm=T),n=n(),.groups="drop")
c<-fc%>%group_by(state,election_year=year)%>%summarise(cev=sum(eligible_voters,na.rm=T),cnv=sum(number_voters,na.rm=T),cvv=sum(valid_votes,na.rm=T),.groups="drop")
x<-inner_join(m,c,by=c("state","election_year"))%>%mutate(r_ev=ev/cev,r_ev0=ev0/cev,r_nv=nv/cnv,r_vv=vv/cvv)
print(as.data.frame(x%>%filter(abs(r_ev-1)>.005|abs(r_nv-1)>.005|abs(r_vv-1)>.005|abs(r_ev0-1)>.005)),row.names=F,digits=4)
