suppressMessages(library(dplyr))
setwd("/Users/hanno/Documents/GitHub/german_election_data")
fu<-readRDS("data/federal_elections/municipality_level/final/federal_muni_unharm.rds")
su<-readRDS("data/state_elections/final/state_unharm.rds")
f<-fu%>%transmute(ags,fy=election_year,fe=eligible_voters_orig)
s<-su%>%transmute(ags,sy=election_year,se=eligible_voters,state)
j<-inner_join(f,s,by="ags",relationship="many-to-many")%>%filter(abs(fy-sy)<=1,fe>0,se>0)%>%mutate(r=se/fe)
g<-j%>%group_by(state,fy,sy)%>%summarise(n=n(),med=median(r),p5=quantile(r,.05),p95=quantile(r,.95),tot=sum(se)/sum(fe),out=mean(r<.8|r>1.25),.groups="drop")
print(as.data.frame(g%>%filter(abs(tot-1)>.04|out>.03)),row.names=F,digits=3)
