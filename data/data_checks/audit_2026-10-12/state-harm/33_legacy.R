suppressMessages({library(dplyr)}); options(width=250)
l <- readRDS("data/state_elections/final/state_harm.rds"); h21 <- readRDS("data/state_elections/final/state_harm_21.rds")
cat(dim(l),"\n"); print(range(l$election_year)); print(grep("^ags|^flag|state_name|date",names(l),value=TRUE)); print(table(l$state)[1:16])
s <- function(x) if (all(is.na(x))) NA_real_ else sum(x,na.rm=T)
a <- l %>% group_by(state,election_year) %>% summarise(ev=s(eligible_voters),vv=s(valid_votes),n=n(),.groups="drop")
b <- h21 %>% group_by(state,election_year) %>% summarise(ev21=s(eligible_voters),vv21=s(valid_votes),n21=n(),.groups="drop")
m <- full_join(a,b,by=c("state","election_year")) %>% mutate(dev=vv/vv21-1, dee=ev/ev21-1)
cat("legacy vs harm_21 state-years: only in legacy:",sum(is.na(m$vv21)),"only in h21:",sum(is.na(m$vv)),"\n")
print(m %>% filter(abs(dev)>0.005|is.na(vv)|is.na(vv21)|abs(dee)>0.005) %>% as.data.frame() %>% head(40))
