suppressMessages({library(dplyr);library(bundeslaendeR)}); options(width=250, dplyr.print_max=400)
u <- readRDS("data/state_elections/final/state_unharm.rds")
bl <- as.data.frame(ltw_elections) %>% mutate(election_date=as.Date(election_date))
cat("RP valid votes: GERDA vs bl\n")
a <- u %>% filter(state=="07") %>% group_by(election_year, election_date) %>% summarise(n=n(), vv_u=sum(valid_votes,na.rm=T), .groups="drop")
b <- bl %>% filter(state=="RP") %>% group_by(election_date) %>% summarise(vv_b=first(valid_votes), nv=first(number_of_voters), .groups="drop")
print(as.data.frame(inner_join(a,b,by="election_date") %>% mutate(d=vv_u/vv_b-1)))
cat("\nRP 1991 party shares GERDA vs bl\n")
x <- u %>% filter(state=="07", election_year==1991); vv<-sum(x$valid_votes,na.rm=T)
g <- sapply(c("cdu","spd","fdp","gruene","rep","other","linke_pds"), function(p) round(100*sum(x[[p]]*x$valid_votes,na.rm=T)/vv,2)); print(g)
print(bl %>% filter(state=="RP", election_date==as.Date("1991-04-21")) %>% select(partyname_short, party_vote_count, party_vshare) %>% arrange(desc(party_vote_count)) %>% head(8))
cat("n municipalities 1991 vs 1996:", nrow(x), nrow(u%>%filter(state=="07",election_year==1996)), "\n")
cat("RP1991 rows with NA/0 valid_votes:", sum(is.na(x$valid_votes)|x$valid_votes==0), "\n")
x2 <- u %>% filter(state=="07", election_year==1996); mm <- inner_join(x%>%select(ags,v91=valid_votes), x2%>%select(ags,v96=valid_votes), by="ags"); cat("corr, ratio sum v91/v96:", sum(mm$v91)/sum(mm$v96), "\n")
mm <- mm %>% mutate(r=v91/v96); print(summary(mm$r)); print(head(mm %>% arrange(r),8))
