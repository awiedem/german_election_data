suppressMessages(library(dplyr))
b <- readRDS(file.path(Sys.getenv("D"),"b.rds"))
cat("--2002 offenders\n")
print(b %>% filter(year==2002, abs(dv)>0.01) %>% mutate(st=substr(ags,1,2)) %>% count(st))
print(b %>% filter(year==2002, abs(dv)>0.01) %>% arrange(desc(abs(dv))) %>% select(ags,number_voters.c,number_voters.m,dv,valid_votes.c,valid_votes.m,n_muni) %>% head(15) %>% as.data.frame)
cat("--1980 offenders\n")
print(b %>% filter(year==1980, abs(dv)>0.01) %>% select(ags,number_voters.c,number_voters.m,dv,eligible_voters.c,eligible_voters.m) %>% as.data.frame)
cat("--1980 eligible\n")
print(b %>% filter(year==1980) %>% summarise(sc=sum(eligible_voters.c), sm=sum(eligible_voters.m)))
print(b %>% filter(year==1980) %>% select(ags,eligible_voters.c,eligible_voters.m,de) %>% head(5) %>% as.data.frame)
cat("--1998 largest\n")
print(b %>% filter(year==1998) %>% arrange(desc(abs(dv))) %>% select(ags,number_voters.c,number_voters.m,dv) %>% head(5) %>% as.data.frame)
cat("--valid mismatch >0.5% any year\n")
print(b %>% filter(abs(dval)>0.005) %>% count(year))
cat("--eligible mismatch >1% by year, post1990\n")
print(b %>% filter(abs(de)>0.01) %>% count(year))
print(b %>% filter(year==2021) %>% arrange(desc(abs(de))) %>% select(ags,eligible_voters.c,eligible_voters.m,de) %>% head(5) %>% as.data.frame)
