suppressMessages({library(dplyr);library(data.table)})
u<-readRDS("data/mayoral_elections/final/mayoral_unharm.rds"); setDT(u)
p<-function(...)cat(...,"\n")
p("ags nchar"); print(table(nchar(u$ags),useNA="a"))
p("state prefix mismatch:",sum(substr(u$ags,1,2)!=u$state))
p("state_name by state"); print(u[,.N,by=.(state,state_name)][order(state)])
p("types"); print(table(u$election_type,u$round))
p("year range"); print(range(u$election_year)); p("year != year(date):",sum(u$election_year!=as.integer(format(u$election_date,"%Y")),na.rm=T)); p("NA date",sum(is.na(u$election_date)))
p("date range");print(range(u$election_date,na.rm=T))
p("dup key (ags,date,type,round):",sum(duplicated(u[,.(ags,election_date,election_type,round)])))
print(u[duplicated(u[,.(ags,election_date,election_type,round)])|duplicated(u[,.(ags,election_date,election_type,round)],fromLast=T)][order(ags,election_date)][1:12])
p("dup key by states"); print(u[duplicated(u[,.(ags,election_date,election_type,round)]),.N,by=state])
# count consistency
p("voters>eligible",sum(u$number_voters>u$eligible_voters,na.rm=T))
p("valid>voters",sum(u$valid_votes>u$number_voters,na.rm=T))
p("valid+inv != voters",sum(abs(u$valid_votes+u$invalid_votes-u$number_voters)>0,na.rm=T))
p("valid+inv != voters >5",sum(abs(u$valid_votes+u$invalid_votes-u$number_voters)>5,na.rm=T))
p("winner_votes>valid",sum(u$winner_votes>u$valid_votes,na.rm=T))
p("turnout out of [0,1]",sum(u$turnout<0|u$turnout>1,na.rm=T), "turnout >=1:",sum(u$turnout>=1,na.rm=T))
p("turnout vs voters/elig diff>0.01",sum(abs(u$turnout-u$number_voters/u$eligible_voters)>0.01,na.rm=T))
p("vs diff>0.01",sum(abs(u$winner_voteshare-u$winner_votes/u$valid_votes)>0.01,na.rm=T))
p("vs out [0,1]",sum(u$winner_voteshare<0|u$winner_voteshare>1,na.rm=T))
p("vs<=0.5 in stichwahl (excl. NA)"); print(u[round=="stichwahl"&winner_voteshare<0.5,.N,by=state])
p("hauptwahl w/ vs<=.5 and flag_superseded F, by state"); print(u[round=="hauptwahl"&winner_voteshare<=0.5,.N,by=.(state,flag_superseded)])
p("NA counts by state");print(u[,lapply(.SD,function(x)sum(is.na(x))),by=state,.SDcols=c("eligible_voters","valid_votes","winner_votes","turnout","winner_voteshare","winner_party")][order(state)])
p("zeros");print(u[,.(elig0=sum(eligible_voters==0,na.rm=T),vv0=sum(valid_votes==0,na.rm=T),wv0=sum(winner_votes==0,na.rm=T),vs0=sum(winner_voteshare==0,na.rm=T),t0=sum(turnout==0,na.rm=T))])
